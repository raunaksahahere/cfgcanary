// Command report renders bench/results/*.json into bench/results/summary.md.
// Every number in the README and docs/benchmarks.md comes from this file.
//
//	go run ./bench/report
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

type env struct {
	CPU       string `json:"cpu"`
	CPUs      int    `json:"cpus"`
	MemoryMB  int    `json:"memory_mb"`
	OS        string `json:"os"`
	Go        string `json:"go"`
	Commit    string `json:"commit"`
	Dirty     bool   `json:"dirty"`
	Timestamp string `json:"timestamp"`
	Command   string `json:"command"`
}

type dist struct {
	N   int     `json:"n"`
	P50 float64 `json:"p50_ms"`
	P90 float64 `json:"p90_ms"`
	P99 float64 `json:"p99_ms"`
	Max float64 `json:"max_ms"`
}

func load(dir, name string, v any) bool {
	b, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		return false
	}
	if err := json.Unmarshal(b, v); err != nil {
		fmt.Fprintf(os.Stderr, "%s: %v\n", name, err)
		os.Exit(1)
	}
	return true
}

func envLine(e env) string {
	d := ""
	if e.Dirty {
		d = " (uncommitted changes)"
	}
	return fmt.Sprintf("_%s, %d threads, %d MB RAM, %s, %s, commit `%s`%s, %s. Command: `%s`._", e.CPU, e.CPUs, e.MemoryMB, e.OS, e.Go, e.Commit, d, e.Timestamp, e.Command)
}

func secs(ms float64) string {
	if ms >= 1000 {
		return fmt.Sprintf("%.2f s", ms/1000)
	}
	return fmt.Sprintf("%.0f ms", ms)
}

func main() {
	dir := "bench/results"
	var b strings.Builder
	b.WriteString("# Benchmark summary\n\nGenerated by `go run ./bench/report` from the raw files in this directory. Do not edit by hand.\n")

	var scale struct {
		Environment env               `json:"environment"`
		Definitions map[string]string `json:"definitions"`
		Results     []struct {
			Agents         int     `json:"agents"`
			ConnectSeconds float64 `json:"connect_seconds"`
			Rings          []struct {
				Ring     int32 `json:"ring"`
				Members  int   `json:"members"`
				Received dist  `json:"received"`
				Applied  dist  `json:"applied"`
				Accepted dist  `json:"accepted"`
				Missing  int   `json:"missing"`
			} `json:"rings"`
			ReleaseSeconds     float64 `json:"release_seconds"`
			RollbackExposed    int     `json:"rollback_exposed"`
			RollbackPerAgent   dist    `json:"rollback_per_agent"`
			RollbackServerSecs float64 `json:"rollback_server_converged_seconds"`
			RollbackMissing    int     `json:"rollback_missing"`
			Server             struct {
				IdleCPUCores         float64 `json:"idle_cpu_cores"`
				IdleRSSMB            float64 `json:"idle_rss_mb"`
				ReleaseCPUCores      float64 `json:"release_cpu_cores"`
				PeakRSSMB            float64 `json:"peak_rss_mb"`
				Goroutines           float64 `json:"goroutines"`
				CPUCoresPer1kIdle    float64 `json:"idle_cpu_cores_per_1k_streams"`
				RSSMBPer1kStreams    float64 `json:"rss_mb_per_1k_streams"`
				ReleaseCPUCoresPer1k float64 `json:"release_cpu_cores_per_1k_streams"`
			} `json:"server"`
			FleetProcessRSSMB float64 `json:"fleet_process_rss_mb"`
		} `json:"results"`
	}
	if load(dir, "scale.json", &scale) {
		b.WriteString("\n## Propagation and rollback at scale (`scale.json`)\n\n" + envLine(scale.Environment) + "\n\n")
		b.WriteString("| Agents | Ring | Members | Received by agent p50 / p99 | Agent applied p50 / p99 | SDK accepted p50 / p99 / max |\n|---:|---:|---:|---|---|---|\n")
		for _, r := range scale.Results {
			for _, rr := range r.Rings {
				fmt.Fprintf(&b, "| %d | %d | %d | %s / %s | %s / %s | %s / %s / %s |\n", r.Agents, rr.Ring, rr.Members,
					secs(rr.Received.P50), secs(rr.Received.P99), secs(rr.Applied.P50), secs(rr.Applied.P99),
					secs(rr.Accepted.P50), secs(rr.Accepted.P99), secs(rr.Accepted.Max))
			}
		}
		b.WriteString("\n| Agents | Rollback: exposed | per-agent p50 / p99 / max | server-reported convergence | Server idle CPU | Server idle RSS | Server CPU during release |\n|---:|---:|---|---|---:|---:|---:|\n")
		for _, r := range scale.Results {
			s := r.Server
			fmt.Fprintf(&b, "| %d | %d | %s / %s / %s | %.2f s | %.3f cores | %.0f MB | %.2f cores |\n", r.Agents, r.RollbackExposed,
				secs(r.RollbackPerAgent.P50), secs(r.RollbackPerAgent.P99), secs(r.RollbackPerAgent.Max), r.RollbackServerSecs,
				s.IdleCPUCores, s.IdleRSSMB, s.ReleaseCPUCores)
		}
		if n := len(scale.Results); n >= 2 {
			lo, hi := scale.Results[0], scale.Results[n-1]
			k := float64(hi.Agents-lo.Agents) / 1000
			fmt.Fprintf(&b, "\nMarginal control-plane cost per 1,000 open streams (slope between %d and %d agents): **%.1f MB RSS** and **%.3f CPU cores idle**. Dividing totals by stream count would overstate this at small N, where the process baseline dominates.\n",
				lo.Agents, hi.Agents, (hi.Server.IdleRSSMB-lo.Server.IdleRSSMB)/k, (hi.Server.IdleCPUCores-lo.Server.IdleCPUCores)/k)
		}
		b.WriteString("\nDefinitions:\n")
		for _, k := range []string{"received", "applied", "accepted", "disk", "rollback", "server", "workload"} {
			fmt.Fprintf(&b, "- **%s**: %s\n", k, scale.Definitions[k])
		}
	}

	var storm struct {
		Environment env               `json:"environment"`
		Definitions map[string]string `json:"definitions"`
		Results     []struct {
			Mode             string  `json:"mode"`
			Agents           int     `json:"agents"`
			DownSeconds      float64 `json:"down_seconds"`
			Attempts         int     `json:"attempts"`
			PeakPer100ms     int     `json:"peak_attempts_per_100ms"`
			PeakPerSecond    int     `json:"peak_attempts_per_second"`
			PeakAfterRestart int     `json:"peak_attempts_per_100ms_after_restart"`
			ReconnectSeconds float64 `json:"seconds_from_restart_to_all_connected"`
		} `json:"results"`
	}
	if load(dir, "storm.json", &storm) {
		b.WriteString("\n## Reconnect storm (`storm.json`, curve in `storm_curve.csv`)\n\n" + envLine(storm.Environment) + "\n\n")
		b.WriteString("| Backoff | Agents | Server down | Attempts | Peak / 100 ms | Peak / s | Peak / 100 ms after restart | Restart to all connected |\n|---|---:|---:|---:|---:|---:|---:|---:|\n")
		for _, r := range storm.Results {
			fmt.Fprintf(&b, "| %s | %d | %.0f s | %d | %d | %d | %d | %.1f s |\n", r.Mode, r.Agents, r.DownSeconds, r.Attempts, r.PeakPer100ms, r.PeakPerSecond, r.PeakAfterRestart, r.ReconnectSeconds)
		}
		b.WriteString("\nDefinitions:\n")
		for _, k := range []string{"attempt", "window", "backoff", "admission"} {
			fmt.Fprintf(&b, "- **%s**: %s\n", k, storm.Definitions[k])
		}
	}

	var blast struct {
		Environment env               `json:"environment"`
		Definitions map[string]string `json:"definitions"`
		Results     []struct {
			System          string  `json:"system"`
			Measured        bool    `json:"measured"`
			Fleet           int     `json:"fleet"`
			Eligible        int     `json:"eligible"`
			Targeted        int     `json:"targeted"`
			AgentApplied    int     `json:"agent_applied"`
			SDKAccepted     int     `json:"sdk_accepted"`
			Affected        int     `json:"affected"`
			DetectSeconds   float64 `json:"time_to_detect_seconds"`
			RollbackSeconds float64 `json:"time_to_rollback_seconds"`
			Notes           string  `json:"notes"`
		} `json:"results"`
	}
	if load(dir, "blast_radius.json", &blast) {
		b.WriteString("\n## Blast radius of a schema-valid, runtime-harmful change (`blast_radius.json`)\n\n" + envLine(blast.Environment) + "\n\n")
		b.WriteString("| System | Measured? | Targeted | Agent applied | SDK accepted | Affected | Time to detect | Time to roll back |\n|---|---|---:|---:|---:|---:|---:|---:|\n")
		for _, r := range blast.Results {
			m := "measured"
			if !r.Measured {
				m = "**model**"
			}
			d, rb := "not detected", "none"
			if r.DetectSeconds >= 0 {
				d = fmt.Sprintf("%.1f s", r.DetectSeconds)
			}
			if r.RollbackSeconds >= 0 {
				rb = fmt.Sprintf("%.2f s", r.RollbackSeconds)
			}
			fmt.Fprintf(&b, "| %s | %s | %d/%d | %d/%d | %d/%d | %d/%d | %s | %s |\n", r.System, m, r.Targeted, r.Fleet, r.AgentApplied, r.Fleet, r.SDKAccepted, r.Fleet, r.Affected, r.Fleet, d, rb)
		}
		b.WriteString("\nNotes:\n")
		for _, r := range blast.Results {
			fmt.Fprintf(&b, "- %s: %s\n", r.System, r.Notes)
		}
		b.WriteString("\nDefinitions:\n")
		for _, k := range []string{"targeted", "agent_applied", "sdk_accepted", "affected", "detect", "rollback", "workload"} {
			fmt.Fprintf(&b, "- **%s**: %s\n", k, blast.Definitions[k])
		}
	}

	var gp struct {
		Environment env               `json:"environment"`
		Model       map[string]string `json:"model"`
		Results     []struct {
			Canary    int     `json:"canary_instances"`
			Control   int     `json:"control_instances"`
			Requests  int     `json:"requests_per_instance_per_look"`
			ICC       float64 `json:"intra_instance_correlation"`
			Delta     float64 `json:"true_degradation"`
			Reps      int     `json:"replications"`
			PPromote  float64 `json:"p_promote"`
			PRollback float64 `json:"p_rollback"`
			PHalt     float64 `json:"p_halt"`
			MeanLooks float64 `json:"mean_looks_to_decision"`
		} `json:"results"`
	}
	if load(dir, "gate_power.json", &gp) {
		b.WriteString("\n## Gate behaviour with 5, 50 and 500 canary instances (`gate_power.json`)\n\n" + envLine(gp.Environment) + "\n\n")
		b.WriteString("Baseline error rate 1%, margin 2 percentage points, 4 looks. Each cell: P(promote) / P(roll back) / P(halt).\n\n")
		b.WriteString("| Canary instances | Requests / instance / look | Heterogeneity (ICC) | no change | +0.5 pp (inside margin) | +2 pp (at margin) | +5 pp (harmful) |\n|---:|---:|---:|---|---|---|---|\n")
		type key struct {
			c, r int
			icc  float64
		}
		rows := map[key][]string{}
		var order []key
		for _, r := range gp.Results {
			k := key{r.Canary, r.Requests, r.ICC}
			if _, ok := rows[k]; !ok {
				order = append(order, k)
			}
			rows[k] = append(rows[k], fmt.Sprintf("%.2f / %.2f / %.2f", r.PPromote, r.PRollback, r.PHalt))
		}
		for _, k := range order {
			fmt.Fprintf(&b, "| %d | %d | %.2f | %s |\n", k.c, k.r, k.icc, strings.Join(rows[k], " | "))
		}
		b.WriteString("\nModel:\n")
		for _, k := range []string{"procedure", "control", "traffic", "heterogeneity", "deltas", "limits"} {
			fmt.Fprintf(&b, "- **%s**: %s\n", k, gp.Model[k])
		}
	}

	var chaos struct {
		Environment env `json:"environment"`
		Scenarios   []struct {
			Name    string  `json:"name"`
			Result  string  `json:"result"`
			Seconds float64 `json:"seconds"`
		} `json:"scenarios"`
		ClientCrashes        int    `json:"client_crashes"`
		ExpectedInitFailures int    `json:"expected_initialization_failures"`
		Notes                string `json:"notes"`
		StateMachineCoverage string `json:"state_machine_statement_coverage"`
	}
	if load(dir, "chaos.json", &chaos) {
		b.WriteString("\n## Chaos suite and client crashes (`chaos.json`)\n\n" + envLine(chaos.Environment) + "\n\n")
		b.WriteString("| Scenario | Result | Duration |\n|---|---|---:|\n")
		for _, s := range chaos.Scenarios {
			fmt.Fprintf(&b, "| %s | %s | %.1f s |\n", s.Name, s.Result, s.Seconds)
		}
		fmt.Fprintf(&b, "\nClient (agent or SDK) crashes across these scenarios: **%d**. Expected, typed initialization failures (cold start with no cache and no bootstrap, asserted by tests): %d. State-machine statement coverage: %s.\n\n%s\n",
			chaos.ClientCrashes, chaos.ExpectedInitFailures, chaos.StateMachineCoverage, chaos.Notes)
	}

	if err := os.WriteFile(filepath.Join(dir, "summary.md"), []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Println("wrote", filepath.Join(dir, "summary.md"))
}
